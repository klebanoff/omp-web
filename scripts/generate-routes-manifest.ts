#!/usr/bin/env bun
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

/**
 * Generates `server/routes-manifest.ts` — a static list of `import()` calls for
 * every route module.
 *
 * The server used to discover routes by scanning `server/routes` at runtime,
 * which a bundler cannot follow: the packaged desktop app has no route `.ts`
 * files on disk. The manifest is the same tree expressed as static imports, so
 * `bun build`/Electrobun carry every module into the bundle. It is committed and
 * checked in CI (`--check`), and `server/routes-manifest.test.mjs` fails when it
 * drifts from the directory.
 */

const ROOT = join(import.meta.dir, "..");
const ROUTES_ROOT = join(ROOT, "server", "routes");
const OUTPUT = join(ROOT, "server", "routes-manifest.ts");

function collectRouteFiles(dir: string): string[] {
  const files: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...collectRouteFiles(full));
    else if (entry.name === "route.ts") files.push(full);
  }
  return files;
}

/** Route keys always use `/`, so the generated file is host-independent. */
function routeKeys(routesRoot = ROUTES_ROOT): string[] {
  return collectRouteFiles(routesRoot)
    .map((file) => relative(routesRoot, file).split(/[\\/]/).join("/"))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

function render(keys: readonly string[]): string {
  const entries = keys.map(
    (key) => `  ${JSON.stringify(key)}: () => import(${JSON.stringify(`./routes/${key}`)}),`,
  );
  return [
    "// Generated by `bun run routes:manifest`; do not edit.",
    "// Static route table: one lazy import per file under server/routes, keyed by",
    "// its path inside that directory. Bundlers follow these imports, so a packaged",
    "// build carries every route module without reading the filesystem.",
    "",
    "export const routeModules: Record<string, () => Promise<Record<string, unknown>>> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

const check = process.argv.includes("--check");
const keys = routeKeys();
const next = render(keys);
const current = (() => {
  try {
    return readFileSync(OUTPUT, "utf8");
  } catch {
    return null;
  }
})();

if (check) {
  if (current !== next) {
    console.error("server/routes-manifest.ts is out of date. Run `bun run routes:manifest`.");
    process.exit(1);
  }
  console.log(`routes manifest up to date (${keys.length} routes)`);
} else {
  writeFileSync(OUTPUT, next);
  console.log(`wrote server/routes-manifest.ts (${keys.length} routes)`);
}
